void _expectFailure(Uint8List bytes, ContractFailureCode code) {
  expect(
    () => decodeRealtimeCoachingEventV2(bytes),
    throwsA(
      isA<ContractFailure>().having((failure) => failure.code, 'code', code),
    ),
  );
}

void main() {
  test('decodes the frozen canonical fixture into immutable closed values', () {
    final event = decodeRealtimeCoachingEventV2(_fixture());

    expect(event.schemaVersion, '2.0');
    expect(event.sequence, BigInt.from(9));
    expect(event.eventType, CoachingEventType.postShotFeedback);
    expect(event.outcomeStatus, CoachingOutcomeStatus.success);
    expect(event.deliveryStatus, CoachingDeliveryStatus.normal);
    expect(event.lineage.shotSequence, BigInt.from(7));
    expect(event.overlay!.coordinateSpace, OverlayCoordinateSpace.tableMm);
    expect(event.overlay!.primitives, hasLength(2));
    expect(
      event.overlay!.primitives.first.semanticRole,
      OverlaySemanticRole.actualCueBallEnd,
    );
    expect(event.speech!.locale, 'zh-CN');
    expect(event.textSummary, '本杆达到已发布训练标准。');
    expect(
      () => event.overlay!.primitives.add(event.overlay!.primitives.first),
      throwsUnsupportedError,
    );
  });

  group('strict object shapes', () {
    final cases = <String, void Function(Map<String, Object?>)>{
      'top level': (root) => root['unknown'] = true,
      'lineage': (root) =>
          (root['lineage']! as Map<String, Object?>)['unknown'] = true,
      'overlay': (root) =>
          (root['overlay']! as Map<String, Object?>)['unknown'] = true,
      'primitive': (root) =>
          ((root['overlay']! as Map<String, Object?>)['primitives']! as List)
                  .first['unknown'] =
              true,
      'point': (root) =>
          (((root['overlay']! as Map<String, Object?>)['primitives']! as List)
                      .first['point']!
                  as Map<String, Object?>)['unknown'] =
              true,
      'zone': (root) =>
          (((root['overlay']! as Map<String, Object?>)['primitives']!
                      as List)[1]['zone']!
                  as Map<String, Object?>)['unknown'] =
              true,
      'speech': (root) =>
          (root['speech']! as Map<String, Object?>)['unknown'] = true,
    };

    for (final entry in cases.entries) {
      test('rejects an unknown field at ${entry.key}', () {
        final root = _fixtureMap();
        entry.value(root);
        _expectFailure(_canonical(root), ContractFailureCode.unknownField);
      });
    }

    test('rejects missing required fields without coercion', () {
      final root = _fixtureMap()..remove('sequence');
      _expectFailure(_canonical(root), ContractFailureCode.missingField);
    });
  });

  group('wire parser and canonical bytes', () {
    test('rejects excessive parser nesting with ContractFailure', () {
      final text = '${'[' * 5000}0${']' * 5000}';
      _expectFailure(
        Uint8List.fromList(utf8.encode(text)),
        ContractFailureCode.invalidJson,
      );
    });

    test(
      'rejects excessive canonical encoder nesting with ContractFailure',
      () {
        Object? value = 0;
        for (var depth = 0; depth < 5000; depth += 1) {
          value = <Object?>[value];
        }
        expect(
          () => canonicalJsonBytes(value),
          throwsA(
            isA<ContractFailure>().having(
              (failure) => failure.code,
              'code',
              ContractFailureCode.invalidJson,
            ),
          ),
        );
      },
    );

    test('rejects a duplicate top-level key', () {
      final text = utf8
          .decode(_fixture())
          .replaceFirst('{', '{"schema_version":"2.0",');
      _expectFailure(
        Uint8List.fromList(utf8.encode(text)),
        ContractFailureCode.duplicateKey,
      );
    });

    test('rejects a duplicate nested key', () {
      final text = utf8
          .decode(_fixture())
          .replaceFirst('"lineage":{', '"lineage":{"schema_version":"1.0",');
      _expectFailure(
        Uint8List.fromList(utf8.encode(text)),
        ContractFailureCode.duplicateKey,
      );
    });

    test('rejects noncanonical whitespace', () {
      final text = utf8.decode(_fixture()).replaceFirst(',', ', ');
      _expectFailure(
        Uint8List.fromList(utf8.encode(text)),
        ContractFailureCode.nonCanonicalJson,
      );
    });

    test('rejects noncanonical key order', () {
      final root = _fixtureMap();
      final reordered = <String, Object?>{
        'schema_version': root['schema_version'],
        ...root,
      };
      _expectFailure(
        Uint8List.fromList(utf8.encode(jsonEncode(reordered))),
        ContractFailureCode.nonCanonicalJson,
      );
    });

    test('rejects bytes over the limit before JSON parsing', () {
      _expectFailure(Uint8List(65537), ContractFailureCode.sizeLimitExceeded);
    });

    test('rejects invalid UTF-8', () {
      _expectFailure(
        Uint8List.fromList(<int>[0x7b, 0xff, 0x7d]),
        ContractFailureCode.invalidUtf8,
      );
    });

    test('rejects trailing bytes', () {
      _expectFailure(
        Uint8List.fromList(<int>[..._fixture(), 0x20]),
        ContractFailureCode.invalidJson,
      );
    });

    for (final number in <String>['9.0', '9e0', '9E+0']) {
      test('rejects unsafe strict integer spelling $number', () {
        final text = utf8
            .decode(_fixture())
            .replaceFirst('"sequence":9', '"sequence":$number');
        _expectFailure(
          Uint8List.fromList(utf8.encode(text)),
          ContractFailureCode.invalidNumber,
        );
      });
    }
  });

  group('identifiers, versions and digests', () {
    test('rejects malformed UUID', () {
      final root = _fixtureMap()..['event_id'] = 'not-a-uuid';
      _expectFailure(_canonical(root), ContractFailureCode.invalidUuid);
    });

    test('rejects noncanonical uppercase UUID', () {
      final root = _fixtureMap()
        ..['event_id'] = 'DC4D9BAD-1CD7-4346-8C70-71B01519ACFB';
      _expectFailure(_canonical(root), ContractFailureCode.invalidUuid);
    });

    test('rejects non-v4 UUID', () {
      final root = _fixtureMap()
        ..['event_id'] = 'dc4d9bad-1cd7-1346-8c70-71b01519acfb';
      _expectFailure(_canonical(root), ContractFailureCode.invalidUuid);
    });

    test('rejects malformed digest', () {
      final root = _fixtureMap()..['content_sha256'] = 'bad';
      _expectFailure(_canonical(root), ContractFailureCode.invalidDigest);
    });

    test('rejects non-lowercase digest', () {
      final root = _fixtureMap()..['content_sha256'] = ('a' * 64).toUpperCase();
      _expectFailure(_canonical(root), ContractFailureCode.invalidDigest);
    });

    for (final version in <String>['3.0', '2.1', '2']) {
      test('rejects unsupported schema version $version', () {
        final root = _fixtureMap()..['schema_version'] = version;
        _expectFailure(
          _canonical(root),
          ContractFailureCode.unsupportedSchemaVersion,
        );
      });
    }
  });

  group('Python-equivalent scalar semantics', () {
    test('accepts the exact Python vector above signed 64-bit range', () {
      final event = decodeRealtimeCoachingEventV2(_pythonLargeIntegerVector());

      expect(event.sequence, BigInt.parse('9223372036854775808'));
      expect(event.eventId, '759a1a7c-d068-43f7-b3b6-9090ec33d0c4');
      expect(
        event.idempotencyKey,
        'b72eb19f5dc787b5e3561752a18d89fdd1156e0b5e12c74f2d4746644a438aff',
      );
      expect(
        event.contentSha256,
        'fd8c2b5800afb945057773d1683cd3c54a45bade4bd6d594caac0398bb8cbb89',
      );
    });

    test('preserves FEFF exactly as Python StringConstraints strip does', () {
      final event = decodeRealtimeCoachingEventV2(_pythonFeffVector());

      expect(event.textSummary, '\ufeff本杆达到已发布训练标准。\ufeff');
      expect(event.speech!.text, event.textSummary);
      expect(
        event.contentSha256,
        'e5bf780a2af99729f1a5e30e4064138c71c4046f7d40efef378dc0714a42aed9',
      );
    });

    test('sorts canonical object keys by Unicode code point like Python', () {
      final encoded = canonicalJsonBytes(<String, Object?>{
        '\u{10000}': 2,
        '\ue000': 1,
      });

      expect(encoded, orderedEquals(utf8.encode('{"\ue000":1,"\u{10000}":2}')));
    });
  });

  test('overlay constructor defensively copies the primitive list', () {
    final source = <OverlayPrimitiveV1>[];
    final overlay = OverlayPayloadV1(
      schemaVersion: '1.0',
      coordinateSpace: OverlayCoordinateSpace.tableMm,
      outcomeStatus: CoachingOutcomeStatus.informational,
      deliveryStatus: CoachingDeliveryStatus.normal,
      primitives: source,
    );

    source.add(
      OverlayPrimitiveV1(
        schemaVersion: '1.0',
        kind: OverlayPrimitiveKind.point,
        semanticRole: OverlaySemanticRole.actualCueBallEnd,
        labelCode: 'retained-mutation',
        lineStyle: OverlayLineStyle.solid,
        point: TablePointMmV1(
          schemaVersion: '1.0',
          xMm: BigInt.zero,
          yMm: BigInt.zero,
        ),
        zone: null,
      ),
    );

    expect(overlay.primitives, isEmpty);
  });

  group('status and lineage invariants', () {
    test('rejects an impossible event status combination', () {
      final root = _fixtureMap()..['event_type'] = 'SETUP';
      _expectFailure(_canonical(root), ContractFailureCode.statusMismatch);
    });

    test('rejects overlay status mismatch', () {
      final root = _fixtureMap();
      (root['overlay']! as Map<String, Object?>)['outcome_status'] = 'FAILURE';
      _expectFailure(_canonical(root), ContractFailureCode.statusMismatch);
    });

    test('rejects speech status mismatch', () {
      final root = _fixtureMap();
      (root['speech']! as Map<String, Object?>)['outcome_status'] = 'FAILURE';
      _expectFailure(_canonical(root), ContractFailureCode.statusMismatch);
    });

    test('rejects speech and summary text mismatch', () {
      final root = _fixtureMap()..['text_summary'] = '不同文本';
      _expectFailure(_canonical(root), ContractFailureCode.statusMismatch);
    });

    test('requires speech for degraded, error, abstained or unsupported', () {
      final root = _fixtureMap()
        ..['event_type'] = 'SYSTEM_STATUS'
        ..['outcome_status'] = 'INFORMATIONAL'
        ..['delivery_status'] = 'ERROR'
        ..['overlay'] = null
        ..['speech'] = null;
      _expectFailure(_canonical(root), ContractFailureCode.statusMismatch);
    });

    for (final missing in <String>[
      'shot_id',
      'shot_sequence',
      'evidence_sha256',
    ]) {
      test('rejects partial shot lineage missing $missing', () {
        final root = _fixtureMap();
        (root['lineage']! as Map<String, Object?>)[missing] = null;
        _expectFailure(_canonical(root), ContractFailureCode.lineageMismatch);
      });
    }

    test('rejects decision lineage without shot lineage', () {
      final root = _fixtureMap();
      final lineage = root['lineage']! as Map<String, Object?>;
      lineage['shot_id'] = null;
      lineage['shot_sequence'] = null;
      lineage['evidence_sha256'] = null;
      _expectFailure(_canonical(root), ContractFailureCode.lineageMismatch);
    });

    test('requires shot and decision lineage for a machine outcome', () {
      final root = _fixtureMap();
      (root['lineage']! as Map<String, Object?>)['decision_id'] = null;
      _expectFailure(_canonical(root), ContractFailureCode.lineageMismatch);
    });
  });

  group('overlay geometry and roles', () {
    test('rejects a point outside 2540 x 1270', () {
      final root = _fixtureMap();
      final primitive =
          ((root['overlay']! as Map<String, Object?>)['primitives']! as List)
                  .first
              as Map<String, Object?>;
      (primitive['point']! as Map<String, Object?>)['x_mm'] = 2541;
      _expectFailure(_canonical(root), ContractFailureCode.overlayGeometry);
    });

    test('rejects a zone outside 2540 x 1270', () {
      final root = _fixtureMap();
      final primitive =
          ((root['overlay']! as Map<String, Object?>)['primitives']! as List)[1]
              as Map<String, Object?>;
      (primitive['zone']! as Map<String, Object?>)['maximum_y_mm'] = 1271;
      _expectFailure(_canonical(root), ContractFailureCode.overlayGeometry);
    });

    test('rejects unordered zone bounds', () {
      final root = _fixtureMap();
      final primitive =
          ((root['overlay']! as Map<String, Object?>)['primitives']! as List)[1]
              as Map<String, Object?>;
      (primitive['zone']! as Map<String, Object?>)['minimum_x_mm'] = 201;
      _expectFailure(_canonical(root), ContractFailureCode.overlayGeometry);
    });

    test('rejects wrong geometry for primitive kind', () {
      final root = _fixtureMap();
      final primitive =
          ((root['overlay']! as Map<String, Object?>)['primitives']! as List)
                  .first
              as Map<String, Object?>;
      primitive['zone'] = <String, Object?>{
        'maximum_x_mm': 200,
        'maximum_y_mm': 400,
        'minimum_x_mm': 100,
        'minimum_y_mm': 300,
        'schema_version': '1.0',
      };
      _expectFailure(_canonical(root), ContractFailureCode.overlayGeometry);
    });

    test('rejects semantic role and kind mismatch', () {
      final root = _fixtureMap();
      final primitive =
          ((root['overlay']! as Map<String, Object?>)['primitives']! as List)
                  .first
              as Map<String, Object?>;
      primitive['semantic_role'] = 'TARGET_ZONE';
      _expectFailure(_canonical(root), ContractFailureCode.overlayGeometry);
    });

    test('rejects STATUS because it has no authoritative v1 geometry', () {
      final root = _fixtureMap();
      final primitive =
          ((root['overlay']! as Map<String, Object?>)['primitives']! as List)
                  .first
              as Map<String, Object?>;
      primitive['semantic_role'] = 'STATUS';
      _expectFailure(_canonical(root), ContractFailureCode.overlayGeometry);
    });

    test('rejects duplicate primitive semantic roles', () {
      final root = _fixtureMap();
      final primitives =
          (root['overlay']! as Map<String, Object?>)['primitives']! as List;
      primitives[1]['semantic_role'] = 'ACTUAL_CUE_BALL_END';
      primitives[1]['kind'] = 'POINT';
      primitives[1]['point'] = primitives[0]['point'];
      primitives[1]['zone'] = null;
      _expectFailure(_canonical(root), ContractFailureCode.overlayGeometry);
    });

    test('rejects noncanonical primitive semantic-role order', () {
      final root = _fixtureMap();
      final overlay = root['overlay']! as Map<String, Object?>;
      overlay['primitives'] = (overlay['primitives']! as List).reversed
          .toList();
      _expectFailure(_canonical(root), ContractFailureCode.overlayGeometry);
    });
  });

  group('domain-separated hashes', () {
    test('rejects event identity mismatch', () {
      final root = _fixtureMap()
        ..['event_id'] = '00000000-0000-4000-8000-000000000012';
      _expectFailure(_canonical(root), ContractFailureCode.hashMismatch);
    });

    test('rejects idempotency key mismatch', () {
      final root = _fixtureMap()..['idempotency_key'] = '0' * 64;
      _expectFailure(_canonical(root), ContractFailureCode.hashMismatch);
    });

    test('rejects content SHA-256 mismatch', () {
      final root = _fixtureMap()..['content_sha256'] = '0' * 64;
      _expectFailure(_canonical(root), ContractFailureCode.hashMismatch);
    });
  });
}
