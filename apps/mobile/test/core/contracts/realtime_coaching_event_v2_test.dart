        'fd8c2b5800afb945057773d1683cd3c54a45bade4bd6d594caac0398bb8cbb89',
      )
      .replaceFirst(
        'dc4d9bad-1cd7-4346-8c70-71b01519acfb',
        '759a1a7c-d068-43f7-b3b6-9090ec33d0c4',
      )
      .replaceFirst(
        'd8038a53e691156548526f7f40772d0944f323d2e5f7f9c14297a6209cc14edf',
        'b72eb19f5dc787b5e3561752a18d89fdd1156e0b5e12c74f2d4746644a438aff',
      )
      .replaceFirst('"sequence":9', '"sequence":9223372036854775808');
  return Uint8List.fromList(utf8.encode(text));
}

