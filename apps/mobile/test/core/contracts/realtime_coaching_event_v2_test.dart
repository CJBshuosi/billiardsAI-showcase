Uint8List _fixture() =>
    File('test/fixtures/realtime_v2/post_shot_success.json').readAsBytesSync();

Map<String, Object?> _fixtureMap() =>
    jsonDecode(utf8.decode(_fixture())) as Map<String, Object?>;

Uint8List _canonical(Object? value) {
  Object? sorted(Object? node) {
    if (node is Map<String, Object?>) {
      final keys = node.keys.toList()..sort();
      return <String, Object?>{for (final key in keys) key: sorted(node[key])};
    }
    if (node is List<Object?>) return node.map(sorted).toList();
    return node;
  }

  return Uint8List.fromList(utf8.encode(jsonEncode(sorted(value))));
}

// Exact values generated by the issuer and canonical serializer archived at
// 6825068e85e4eecfe89a19b8a8854fb4c2f454dd.
Uint8List _pythonLargeIntegerVector() {
  var text = utf8.decode(_fixture());
  text = text
      .replaceFirst(
